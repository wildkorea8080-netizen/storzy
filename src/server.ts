server.listen(config.port, () => {
  logger.info("server.started", { port: config.port });
});

let shutdownPromise:Promise<void>|undefined;
function shutdown(signal:"SIGINT"|"SIGTERM"):Promise<void>{
  if(shutdownPromise)return shutdownPromise;
  shutdownPromise=(async()=>{
    readiness.markDraining();
    logger.info("server.draining",{signal,drainMs:config.shutdownDrainMs});
    await new Promise(resolve=>setTimeout(resolve,config.shutdownDrainMs));
    let timedOut=false;
    await new Promise<void>(resolve=>{const timer=setTimeout(()=>{timedOut=true;server.closeAllConnections();resolve()},config.shutdownTimeoutMs-config.shutdownDrainMs);server.close(()=>{clearTimeout(timer);resolve()})});
    await pool.end();
    logger.info("server.stopped",{signal,timedOut});
  })();
  return shutdownPromise;
}

process.once("SIGINT",()=>void shutdown("SIGINT"));
process.once("SIGTERM",()=>void shutdown("SIGTERM"));
