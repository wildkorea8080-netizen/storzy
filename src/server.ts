const shopifyOAuth=connectionRepository&&shopifyApiKey&&shopifyApiSecret&&shopifyCallback&&shopifyScopes.length?new ShopifyOAuthService(pool,connectionRepository,{apiKey:shopifyApiKey,apiSecret:shopifyApiSecret,callbackUrl:shopifyCallback,scopes:shopifyScopes}):undefined;
